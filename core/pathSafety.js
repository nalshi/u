// ========================================================
// 🛡️ تحقق دفاعي (defense in depth) من أجزاء المسار المستخدمة لبناء
// مسارات ملفات على مزوّدي تخزين خارجيين (GitHub وغيره) أو مفاتيح على
// قواعد بيانات لحظية (Firebase). حتى لو كانت القيمة (مثل username أو
// productId) موثوقة أصلاً من طبقة أخرى، نمنع هنا وبشكل مركزي أي قيمة
// تحتوي فواصل مسار أو "../" حتى لا تُستخدم لكتابة/قراءة مسار خارج النطاق
// المقصود (اجتياز مسار / Path Traversal) لو حدث أي خلل بطبقة التحقق الأولى.
// ========================================================
export function assertSafePathSegment(value, label = 'قيمة') {
  const str = value === null || value === undefined ? '' : String(value);
  if (!str || str === '.' || str === '..' || /[\/\\]|\.\.|\x00/.test(str)) {
    throw new Error(`${label} غير صالحة لاستخدامها ضمن مسار ملف: ${JSON.stringify(str).slice(0, 100)}`);
  }
  return str;
}
